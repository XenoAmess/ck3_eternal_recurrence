template <std::size_t Size>
bool BytesMatch(std::uintptr_t address,
                const std::array<std::uint8_t, Size> &expected) noexcept {
  return std::memcmp(reinterpret_cast<const void *>(address), expected.data(),
                     expected.size()) == 0;
}

