"""Render reviewed exact4 relic UI entry pins; no EXE or game access."""
from pathlib import Path
import argparse,hashlib,json

def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--source-pins',type=Path,required=True)
 parser.add_argument('--output',type=Path,required=True)
 args=parser.parse_args()
 value=json.loads(args.source_pins.read_text(encoding='utf-8'))
 if value['exe_sha256'].lower()!='98702f88a547cde2eaf29a85f93b85f68ee4cf8148336a4f7afaeb75319dd518':raise ValueError('Foreign build')
 lines=['// GENERATED by generate_holy_site_relic_actions_pins.py from source-prefix-pins.json; do not edit.\n',
  'constexpr std::array<std::pair<std::uintptr_t,std::string_view>,'+str(len(value['pins']))+'> kRelicActionPins{{\n']
 for pin in value['pins']:
  raw=bytes.fromhex(pin['prefix_hex'])
  if not 1<=len(raw)<=64 or hashlib.sha256(raw).hexdigest()!=pin['prefix_sha256']:raise ValueError('Invalid prefix bytes/SHA')
  lines.append(' {0x'+format(pin['entry_rva'],'X')+',"'+raw.hex()+'"},\n')
 lines.append('}};\n')
 args.output.parent.mkdir(parents=True,exist_ok=True)
 args.output.write_text(''.join(lines),encoding='utf-8',newline='\n')

if __name__=='__main__':main()
