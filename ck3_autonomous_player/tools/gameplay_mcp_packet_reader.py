"""Source-aware Runtime32/R77 SDK; reuse registry, qualify the new paused frame.

Reuses Root existing registry qualification, waits on partial core loading observations,
and consumes one new full Snapshot. Later
requests use the same file inbox as the existing Root SDK helper. No gameplay
action or checkpoint save is generated by this file.
"""
from __future__ import annotations

import argparse
import asyncio
from datetime import datetime, timezone
import json
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

from wait_restored_ck3_core_12004 import wait_for_restored_core_v1

GAME_SHA = "98702f88a547cde2eaf29a85f93b85f68ee4cf8148336a4f7afaeb75319dd518"


def read(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def write(path: Path, value: dict) -> None:
    with path.open("x", encoding="utf-8") as stream:
        stream.write(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def verify_snapshot(body: dict, expected: dict) -> dict:
    import win32gui
    import win32process

    character = body.get("played_character")
    character = character if isinstance(character, dict) else {}
    diagnostics = body.get("diagnostics")
    diagnostics = diagnostics if isinstance(diagnostics, dict) else {}
    hello = diagnostics.get("hello")
    hello = hello if isinstance(hello, dict) else {}
    pid = hello.get("pid")
    windows = []

    def inspect(hwnd, unused):
        if win32process.GetWindowThreadProcessId(hwnd)[1] == pid and win32gui.IsWindowVisible(hwnd):
            windows.append({"hwnd": hwnd, "pid": pid, "minimized": bool(win32gui.IsIconic(hwnd))})

    if isinstance(pid, int):
        win32gui.EnumWindows(inspect, None)
    checks = {
        "restored_recovery_date": body.get("date_raw") == expected["expected_date_raw"],
        "recovery_episode": body.get("episode_run_id") == expected["expected_episode_run_id"],
        "paused": body.get("paused") is expected["expected_paused"],
        "map_ready": body.get("map_ready") is True,
        "recovery_character_alive": character.get("character_id") == expected["expected_character_id"] and character.get("alive") is True,
        "native_snapshot_identity": isinstance(body.get("snapshot_id"), str) and body["snapshot_id"].startswith("native:"),
        "native_revision": type(body.get("native_revision")) is int and body["native_revision"] > 0,
        "military_and_war_collections": isinstance(body.get("player_armies"), list) and isinstance(body.get("active_wars"), list),
        "actual4_version": hello.get("expected_ck3_version") == "1.20.0.4",
        "actual4_exe": str(hello.get("expected_ck3_sha256", "")).lower() == GAME_SHA,
        "actual4_adapter": hello.get("game_adapter_id") == "ck3-1.20.0.4-msvc-x64",
        "owned_game_minimized": bool(windows) and all(row["minimized"] for row in windows),
    }
    return {"checks": checks, "windows": windows, "status": "GREEN" if all(checks.values()) else "RED"}


async def main(packet: Path, sdk_source_root: Path, sdk_source_head: str,
               recovery_input_packet: Path, registry_reuse_reference: Path,
               sdk_source_metadata: Path,
               allow_private_construction_formal_trial: bool = False,
                *, warm_resume: dict | None = None) -> None:
    draft = read(packet / "BOOTSTRAP-DRAFT.json")
    recovery = read(recovery_input_packet)
    expected = {
        "tool": "ck3_take_snapshot", "arguments": {"include_native_command_history": False},
        "expected_character_id": recovery["expected_character_id"],
        "expected_date_raw": recovery["expected_date_raw"],
        "expected_episode_run_id": recovery["expected_episode_run_id"],
        "expected_paused": recovery["expected_paused"],
    }
    handoff = read(packet / "ROOT-OPERATOR-HANDOFF.json")
    if handoff.get("result") != "ACCEPTED":
        raise ValueError("the actual new managed handoff must be accepted first")
    inbox, outbox = packet / "gameplay-requests", packet / "gameplay-responses"
    inbox.mkdir(exist_ok=True)
    outbox.mkdir(exist_ok=True)
    argv = list(draft["gameplay_mcp"]["argv"])
    entrypoint_index = next(index for index, item in enumerate(argv)
                            if item.endswith("mcp_server.py"))
    argv[entrypoint_index] = str(sdk_source_root / "ck3_autonomous_player" / "mcp_server.py")
    if "--private-prisoner-ransom-action" not in argv:
        argv.append("--private-prisoner-ransom-action")
    if "--allow-private-family-marriage-formal-trial" not in argv:
        argv.append("--allow-private-family-marriage-formal-trial")
    if (allow_private_construction_formal_trial
            and "--allow-private-construction-formal-trial" not in argv):
        argv.append("--allow-private-construction-formal-trial")
    completed_exit_request = None
    warm_output = None
    if warm_resume is not None:
        # A normal close receipt belongs to the exact final request, not a
        # general permission to discard pending or historical requests.
        close = read(Path(warm_resume["normal_sdk_exit_receipt"]))
        completed_exit_request = Path(close["exit_request"])
        if (close["normal_sdk_exit_confirmed"] is not True
                or close["exit_code"] != 0
                or close["Game_exit_requested"] is not False
                or completed_exit_request.parent != inbox
                or completed_exit_request.name != warm_resume["expected_exit_request_name"]
                or read(completed_exit_request).get("exit_client") is not True):
            raise ValueError("warm resume requires the exact successful final SDK exit")
        argv = list(warm_resume["mcp_argv"])
        if argv[next(index for index, item in enumerate(argv)
                     if item.endswith("mcp_server.py"))] != str(
                         sdk_source_root / "ck3_autonomous_player" / "mcp_server.py"):
            raise ValueError("warm MCP entrypoint differs from the frozen full SDK")
        warm_output = Path(warm_resume["evidence_directory"])
        warm_output.mkdir(parents=True, exist_ok=True)
    flags = draft["restored_original_switches"]
    if len(flags) != 20 or any(flag not in argv for flag in flags):
        raise ValueError("the exact restored 20 private SDK flags are required")
    # Root supplied prior registry evidence is referenced, never replayed.
    # State, pipe, Python and original flags stay in the managed draft; the
    # requested SDK source entrypoint and cwd are supplied independently.
    params = StdioServerParameters(command=argv[0], args=argv[1:],
                                  cwd=str(sdk_source_root))
    stderr_path = ((warm_output / "ROOT-WARM-GAMEPLAY-SERVER-STDERR.log")
                   if warm_output is not None else
                   (packet / "ROOT-GAMEPLAY-SERVER-STDERR-FIRST77.log"))
    with stderr_path.open("x", encoding="utf-8") as err:
        async with stdio_client(params, errlog=err) as (read_stream, write_stream):
            async with ClientSession(read_stream, write_stream) as session:
                await session.initialize()
                snapshot_path = None
                if warm_resume is not None:
                    write(warm_output / "ROOT-WARM-TRANSPORT-ATTACHED.json", {
                        "status": "MCP_INITIALIZED_RESTORE_NOT_YET_OBSERVED",
                        "source_head": sdk_source_head,
                        "sdk_source_root": str(sdk_source_root),
                        "sdk_source_metadata": str(sdk_source_metadata),
                        "native_source_head": draft["native"]["source_head"],
                        "run_identity": draft["run_identity"],
                        "operator_packet": str(packet),
                        "normal_sdk_exit_receipt": warm_resume["normal_sdk_exit_receipt"],
                        "skipped_successful_exit_request": str(completed_exit_request),
                        "startup_core_queries": 0, "startup_full_snapshot_queries": 0,
                        "checkpoint_save_added": False,
                        "Game_stop_or_launch_requested": False,
                        "qualification_of_recovery_or_business_inferred": False,
                    })
                    print("READY warm transport initialized; same-PID restore awaits next ordinary request", flush=True)
                else:
                    write(packet / "ROOT-REGISTRY-REUSED-FIRST77.json", {
                        "status": "REUSED_PRIOR_ROOT_QUALIFICATION",
                        "reference": str(registry_reuse_reference),
                        "accepted_migration_baseline_count": 208,
                        "expected_current_count": 211,
                        "new_list_tools_calls": 0,
                        "source_head": sdk_source_head,
                        "sdk_source_root": str(sdk_source_root),
                        "sdk_source_metadata": str(sdk_source_metadata),
                        "native_source_head": draft["native"]["source_head"],
                        "qualification_of_new_native_domain_inferred": False,
                    })
                    core_wait = await wait_for_restored_core_v1(
                        session, expected)
                    core_wait.update(source_head=sdk_source_head, sdk_source_root=str(sdk_source_root),
                                     recovery_input_packet=str(recovery_input_packet),
                                     run_identity=draft["run_identity"])
                    write(packet / "ROOT-COLD-LOAD-CORE-WAIT-FIRST77.json", core_wait)
                    if core_wait["status"] != "CORE_READY_FOR_FULL_SNAPSHOT":
                        print("CORE", core_wait["status"], flush=True)
                        return
                    # R0053 proved a 250ms full-frame cache window. Expire it
                    # after core readiness before the original single full query.
                    await asyncio.sleep(.35)
                    snapshot_path = inbox / "001-runtime32-r77-paused-snapshot.json"
                    write(snapshot_path, expected)
                    print("READY registry reused; one new Runtime32 full Snapshot queued", flush=True)
                while True:
                    for request_path in sorted(inbox.glob("*.json")):
                        response_path = outbox / request_path.name
                        if response_path.exists():
                            continue
                        if request_path == completed_exit_request:
                            continue
                        request = read(request_path)
                        if request.get("exit_client"):
                            return
                        started = datetime.now(timezone.utc).isoformat()
                        try:
                            result = await session.call_tool(request["tool"], request.get("arguments", {}))
                            response = {"started_at_utc": started, "ended_at_utc": datetime.now(timezone.utc).isoformat(),
                                        "request": request, "result": result.model_dump(mode="json")}
                        except Exception as error:
                            response = {"started_at_utc": started, "ended_at_utc": datetime.now(timezone.utc).isoformat(),
                                        "request": request, "client_error": repr(error)}
                        write(response_path, response)
                        if request_path == snapshot_path:
                            raw = response.get("result", {})
                            observed = raw.get("structuredContent", raw.get("structured_content"))
                            if not isinstance(observed, dict):
                                for block in raw.get("content", []):
                                    if block.get("type") == "text":
                                        try:
                                            candidate = json.loads(block["text"])
                                        except (TypeError, ValueError):
                                            continue
                                        if isinstance(candidate, dict):
                                            observed = candidate
                                            break
                            qualification = verify_snapshot(observed, expected) if isinstance(observed, dict) and not raw.get("isError", raw.get("is_error", False)) else {"status": "RED", "checks": {"successful_structured_snapshot": False}, "windows": []}
                            receipt = {
                                **qualification, "observed_at_utc": datetime.now(timezone.utc).isoformat(),
                                "source_head": sdk_source_head, "sdk_source_root": str(sdk_source_root),
                                "sdk_source_metadata": str(sdk_source_metadata),
                                "bootstrap_source_head": draft.get("source_head"), "whole_response": str(response_path),
                                "native_source_head": draft["native"]["source_head"],
                                "native_qualification_receipt": draft["native"].get("qualification_receipt"),
                                "run_identity": draft["run_identity"],
                                "new_query_count": core_wait["core_query_count"] + 1,
                                "readiness_core_query_count": core_wait["core_query_count"],
                                "full_snapshot_query_count": 1,
                                "core_wait_reference": str(packet / "ROOT-COLD-LOAD-CORE-WAIT-FIRST77.json"),
                                "g2_days_advanced": 0, "checkpoint_save_added": False,
                                "g2_resume_ready": False,
                                "recovery_input_packet": str(recovery_input_packet),
                                "recovery_freeze_reference": recovery["recovery_freeze_reference"],
                                "saved_normal_days": recovery["saved_normal_days"],
                                "checkpoint_created_in_recovery_input": recovery["checkpoint_created"],
                                "recovery_result_reference": recovery["recovery_result_reference"],
                                "prior_operator_packet": recovery["prior_operator_packet"],
                                "remaining": "New DLL32 startup and paused frame qualification only; the recovery input supplies its checkpoint, date and episode. No old four-family qualification is rerun.",
                            }
                            write(packet / "ROOT-FULL-RUNTIME30-PAUSED-SNAPSHOT-FIRST77.json", receipt)
                            if qualification["status"] == "GREEN":
                                write(packet / "ROOT-FULL-RUNTIME30-PAUSED-SNAPSHOT-QUALIFIED-FIRST77.json", receipt)
                            print("SNAPSHOT", qualification["status"], flush=True)
                        print("DONE", request_path.name, flush=True)
                    await asyncio.sleep(.25)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--packet", type=Path, required=True)
    parser.add_argument("--sdk-source-root", type=Path, required=True)
    parser.add_argument("--sdk-source-head", required=True)
    parser.add_argument("--sdk-source-metadata", type=Path, required=True)
    parser.add_argument("--recovery-input-packet", type=Path, required=True,
                        help="Root small flat recovery JSON file; no save/state payload")
    parser.add_argument("--registry-reuse-reference", type=Path, required=True)
    parser.add_argument("--allow-private-construction-formal-trial", action="store_true")
    args = parser.parse_args()
    asyncio.run(main(args.packet, args.sdk_source_root, args.sdk_source_head,
                     args.recovery_input_packet, args.registry_reuse_reference,
                     args.sdk_source_metadata, args.allow_private_construction_formal_trial))
