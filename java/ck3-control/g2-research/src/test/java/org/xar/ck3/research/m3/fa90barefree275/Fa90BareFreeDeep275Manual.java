private static void assertNormal(CaseSpec spec, Fixture fixture, QueueFp604Api.Outcome actual) {
    Checks.that(!spec.stopped(), spec.id() + " Normal case");
    Checks.that(actual instanceof QueueFp604Api.Normal, spec.id() + " actual is Normal");
    QueueFp604Api.Normal normal = (QueueFp604Api.Normal) actual;

    // Compare complete 185.NormalReturn V/N/RIP/callerSP
    GovernmentCrtBoundary185Api.NormalReturn actualReturn = normal.base().normalReturn();
    GovernmentCrtBoundary185Api.NormalReturn expectedReturn = spec.expectedNormal().base().normalReturn();
    Checks.eq(actualReturn.volatileBits(), expectedReturn.volatileBits(), spec.id() + " Normal V");
    Checks.eq(actualReturn.nonvolatileBits(), expectedReturn.nonvolatileBits(), spec.id() + " Normal N");
    Checks.eq(actualReturn.returnRipBits(), expectedReturn.returnRipBits(), spec.id() + " Normal RIP");
    Checks.eq(actualReturn.callerRspBits(), expectedReturn.callerRspBits(), spec.id() + " Normal SP");

    // Compare postDF
    Checks.eq(normal.base().postDirectionFlagSet(), spec.expectedNormal().base().postDirectionFlagSet(), spec.id() + " Normal DF");

    // SAME partialMxcsr object (not equal-only/defaultreconstruction)
    Checks.same(normal.postMxcsr(), spec.expectedNormal().postMxcsr(), spec.id() + " Normal MXCSR identity");

    // Check fullRam.traceSnapshot vs spec.trace()
    Checks.eq(fixture.ram.traceSnapshot(), spec.trace(), spec.id() + " exact normal RAM trace");

    // FullRAM serializedSha256 vs spec.finalHash()
    Checks.eq(fixture.ram.serializedSha256(), spec.finalHash(), spec.id() + " whole finite normal RAM hash");

    // AtomicCallCount vs spec.expectedAtomics()
    Checks.eq(fixture.ram.atomicCallCount(), spec.expectedAtomics(), spec.id() + " normal atomic count");

    // Compare fixture counters against real expected accessors
    Checks.eq(fixture.mandatoryCalls, spec.expectedMandatoryCalls(), spec.id() + " mandatory callback count");
    Checks.eq(fixture.internalCalls, spec.expectedInternalCalls(), spec.id() + " internal callback count");
    Checks.eq(fixture.callbackFrames, spec.expectedCallbackFrames(), spec.id() + " two public callback frames");
    Checks.eq(fixture.budgetCalls, spec.expectedBudgetCalls(), spec.id() + " budget count");
    Checks.eq(fixture.rootForeignCalls, spec.expectedRootForeignCalls(), spec.id() + " root foreign count");
    Checks.eq(fixture.remainingTailCalls, spec.expectedRemainingTailCalls(), spec.id() + " no opaque E364 tail");
    Checks.eq(fixture.sutInvocations, spec.expectedSutInvocations(), spec.id() + " direct267 once");

    // CallbackIdsSnapshot must equal List.of("mandatory689C","bare61first")
    Checks.eq(fixture.callbackIdsSnapshot(), List.of("mandatory689C", "bare61first"), spec.id() + " public callback order only");
}

