package org.xar.ck3.rrf;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.xar.ck3.rrf.Contracts.Catalog;
import org.xar.ck3.rrf.Contracts.GeneratedFiles;
import org.xar.ck3.rrf.Contracts.Product;

/** Actual source/staging consumer: validates bytes, producer closure, references and declared localization formats. */
public final class ContentValidator {
    private static final Pattern REFERENCE = Pattern.compile("\\brrf_[A-Za-z0-9_]+_(?:effect|trigger|value)\\b");
    private static final Pattern SCRIPTED_GUI = Pattern.compile("GetScriptedGui\\(\\s*'(?<name>rrf_[A-Za-z0-9_]+)'\\s*\\)");
    private static final Pattern LOCALIZATION = Pattern.compile("^ ([A-Za-z_][A-Za-z0-9_]*):[0-9]* \\\"((?:[^\\\"\\\\]|\\\\.)*)\\\"\\s*$");
    private static final Pattern PROTECTED_TOKEN = Pattern.compile("\\[[^\\[\\]\\r\\n]+\\]|\\$[^$\\r\\n]+\\$|@[A-Za-z0-9_.:/-]+!|#[A-Za-z0-9_]+|#!|§.|\\\\.");
    private static final Pattern LOC_REFERENCE = Pattern.compile("(?:\\$((?:rrf_|RRF_)[A-Za-z0-9_]+)\\$|\\b(?:text|desc|tooltip|title|confirm_text|localization_key)\\s*=\\s*\\\"?((?:rrf_|RRF_)[A-Za-z0-9_]+)\\\"?)");
    private ContentValidator() { }
    public record Validation(String version, int runtimeFiles, int definitions, int blockedDefinitions) { }
    public record RuntimeProduct(Product product, List<String> files, Catalog catalog) {
        public RuntimeProduct { files = List.copyOf(files); }
    }
    public static RuntimeProduct product(Path source) throws IOException {
        Product product = Json.read(Files.readAllBytes(source.resolve("tools/product.json")), Product.class);
        byte[] catalogBytes = Files.readAllBytes(source.resolve("catalog/generated-catalog.json"));
        Catalog catalog = Json.read(catalogBytes, Catalog.class);
        GeneratedFiles generated = Json.read(Files.readAllBytes(source.resolve("catalog/generated-files.json")), GeneratedFiles.class);
        if (!generated.catalogSha256().equals(ReleaseBuilder.sha256(catalogBytes))) throw new IllegalArgumentException("catalog source hash differs");
        Map<String, String> expected = new CatalogGenerator().render(catalog);
        if (!generated.runtimeFiles().equals(List.copyOf(expected.keySet()))) throw new IllegalArgumentException("generated manifest differs from actual producer");
        for (Map.Entry<String, String> file : expected.entrySet()) {
            String expectedBytes = "\ufeff# Generated by religious-ritual-fusion Java tools; edit the producer, then generate.\n" + file.getValue();
            if (!Files.readString(source.resolve(file.getKey()), StandardCharsets.UTF_8).equals(expectedBytes)) throw new IllegalArgumentException("generated file drift: " + file.getKey());
        }
        List<String> paths = new ArrayList<>(product.runtimeFiles()); paths.addAll(generated.runtimeFiles()); Contracts.unique(paths);
        return new RuntimeProduct(product, paths, catalog);
    }
    public static Validation validate(Path source) throws IOException {
        RuntimeProduct product = product(source);
        validateTree(source, product);
        return new Validation(product.product().version(), product.files().size(), product.catalog().definitions().size(), (int) product.catalog().definitions().stream().filter(d -> !d.blockedReasons().isEmpty()).count());
    }
    public static void validateTree(Path directory, RuntimeProduct product) throws IOException {
        Set<String> actual = inventory(directory, false).keySet();
        if (!actual.equals(Set.copyOf(product.files()))) {
            Set<String> missing = new LinkedHashSet<>(product.files()); missing.removeAll(actual);
            Set<String> extra = new LinkedHashSet<>(actual); extra.removeAll(product.files());
            throw new IllegalArgumentException("runtime inventory mismatch, missing=" + missing + ", extra=" + extra);
        }
        Set<String> definitions = new LinkedHashSet<>(); Set<String> guiDefinitions = new LinkedHashSet<>();
        Map<String, String> documents = new LinkedHashMap<>();
        for (String relative : product.files()) {
            byte[] bytes = Files.readAllBytes(directory.resolve(relative)); validateBytes(relative, bytes);
            if (relative.endsWith(".txt") || relative.endsWith(".gui") || relative.equals("descriptor.mod")) {
                String text = new String(bytes, StandardCharsets.UTF_8);
                Clausewitz.Block ast = Clausewitz.parse(text); documents.put(relative, ast.body());
                if (relative.startsWith("common/scripted_effects/") || relative.startsWith("common/scripted_triggers/") || relative.startsWith("common/script_values/")) {
                    if (relative.contains("rrf_catalog_") && ast.entries().size() > 10) throw new IllegalArgumentException("generated file exceeds ten definitions: " + relative);
                    for (Clausewitz.Entry entry : ast.entries()) if (!definitions.add(entry.key())) throw new IllegalArgumentException("duplicate public script: " + entry.key());
                }
                if (relative.startsWith("common/scripted_guis/")) for (Clausewitz.Entry entry : ast.entries()) guiDefinitions.add(entry.key());
            }
        }
        for (Map.Entry<String, String> document : documents.entrySet()) {
            Matcher reference = REFERENCE.matcher(document.getValue());
            while (reference.find()) if (!definitions.contains(reference.group())) throw new IllegalArgumentException("unresolved script in " + document.getKey() + ": " + reference.group());
            Matcher gui = SCRIPTED_GUI.matcher(document.getValue());
            while (gui.find()) if (!guiDefinitions.contains(gui.group("name"))) throw new IllegalArgumentException("unresolved scripted GUI: " + gui.group("name"));
        }
        Map<String, String> english = localization(directory, product.files(), "english");
        Set<String> languages = new LinkedHashSet<>(List.of("english", "simp_chinese"));
        for (String file : product.files()) if (file.startsWith("localization/") && file.endsWith(".yml")) languages.add(file.split("/")[1]);
        for (String language : languages) {
            Map<String, String> localized = localization(directory, product.files(), language);
            if (!english.keySet().equals(localized.keySet())) throw new IllegalArgumentException("localization keys differ: " + language);
            for (String key : english.keySet()) if (!protectedTokens(english.get(key)).equals(protectedTokens(localized.get(key)))) throw new IllegalArgumentException("localization protected tokens differ: " + language + ": " + key);
        }
        for (Map.Entry<String, String> document : documents.entrySet()) {
            Matcher loc = LOC_REFERENCE.matcher(document.getValue());
            while (loc.find()) { String key = loc.group(1) == null ? loc.group(2) : loc.group(1); if (!english.containsKey(key)) throw new IllegalArgumentException("unresolved localization in " + document.getKey() + ": " + key); }
        }
        String descriptor = Files.readString(directory.resolve("descriptor.mod"), StandardCharsets.UTF_8);
        String version = Clausewitz.parse(descriptor).atom("version", "").replace("\"", "");
        if (!version.equals(product.product().version())) throw new IllegalArgumentException("descriptor version differs from product");
        String picture = Clausewitz.parse(descriptor).atom("picture", "").replace("\"", "");
        if (!picture.isEmpty() && !product.files().contains(picture)) throw new IllegalArgumentException("descriptor picture missing from allowlist");
    }
    public static Map<String, Path> inventory(Path root, boolean all) throws IOException {
        Map<String, Path> result = new LinkedHashMap<>();
        try (var paths = Files.walk(root)) {
            for (Path path : paths.filter(Files::isRegularFile).sorted().toList()) {
                if (Files.isSymbolicLink(path)) throw new IllegalArgumentException("symlink payload: " + path);
                String relative = root.relativize(path).toString().replace('\\', '/');
                if (all || relative.equals("descriptor.mod") || relative.equals("thumbnail.png") || relative.startsWith("common/") || relative.startsWith("gui/") || relative.startsWith("localization/") || relative.startsWith("gfx/")) result.put(relative, path);
            }
        }
        return result;
    }
    public static void validateBytes(String path, byte[] bytes) {
        Contracts.safeRuntimePath(path);
        boolean bom = bytes.length >= 3 && bytes[0] == (byte) 0xef && bytes[1] == (byte) 0xbb && bytes[2] == (byte) 0xbf;
        if ((path.endsWith(".txt") || path.endsWith(".gui") || path.endsWith(".yml")) && !bom) throw new IllegalArgumentException("UTF-8 BOM missing: " + path);
        if (path.equals("descriptor.mod")) {
            if (bom) throw new IllegalArgumentException("descriptor must have no BOM");
            if (new String(bytes, StandardCharsets.UTF_8).contains("remote_file_id")) throw new IllegalArgumentException("internal Workshop remote ID");
        }
        if (bytes.length == 0) throw new IllegalArgumentException("empty runtime file: " + path);
        if (path.endsWith(".gui")) validateGuiQuotedEscapes(path, new String(bytes, StandardCharsets.UTF_8));
        if (path.equals("thumbnail.png") && (bytes.length < 8 || bytes[0] != (byte) 0x89 || bytes[1] != 'P' || bytes[2] != 'N' || bytes[3] != 'G' || bytes[4] != 13 || bytes[5] != 10 || bytes[6] != 26 || bytes[7] != 10)) throw new IllegalArgumentException("invalid PNG thumbnail");
    }
    /** Only the GUI lexer rule observed in R0011; this is not an engine grammar validator. */
    private static void validateGuiQuotedEscapes(String path, String text) {
        boolean quoted = false;
        boolean comment = false;
        int line = 1;
        int column = 0;
        for (int index = 0; index < text.length(); index++) {
            char current = text.charAt(index);
            if (current == '\n') { line++; column = 0; comment = false; continue; }
            if (current != '\ufeff') column++;
            if (comment) continue;
            if (!quoted) {
                if (current == '#') comment = true;
                else if (current == '"') quoted = true;
                continue;
            }
            if (current == '"') { quoted = false; continue; }
            if (current != '\\') continue;
            int escapeColumn = column;
            if (index + 1 >= text.length()
                    || (text.charAt(index + 1) != '\\' && text.charAt(index + 1) != '"')) {
                throw new IllegalArgumentException("invalid GUI quoted escape at " + path + ":" + line + ":" + escapeColumn
                        + ": backslash must be followed by quote or backslash");
            }
            index++;
            column++;
        }
    }
    private static Map<String, Long> protectedTokens(String value) {
        Map<String, Long> result = new LinkedHashMap<>(); Matcher tokens = PROTECTED_TOKEN.matcher(value);
        while (tokens.find()) result.merge(tokens.group(), 1L, Long::sum);
        return result;
    }
    private static Map<String, String> localization(Path directory, List<String> files, String language) throws IOException {
        Map<String, String> result = new LinkedHashMap<>();
        for (String file : files) {
            if (!file.startsWith("localization/" + language + "/")) continue;
            List<String> lines = Files.readAllLines(directory.resolve(file), StandardCharsets.UTF_8);
            if (lines.isEmpty() || !lines.getFirst().equals("\ufeffl_" + language + ":")) throw new IllegalArgumentException("wrong localization header: " + file);
            for (String line : lines.subList(1, lines.size())) {
                if (line.isBlank() || line.stripLeading().startsWith("#")) continue;
                Matcher matcher = LOCALIZATION.matcher(line);
                if (!matcher.matches() || result.putIfAbsent(matcher.group(1), matcher.group(2)) != null) throw new IllegalArgumentException("invalid or duplicate localization: " + file + ": " + line);
            }
        }
        if (result.isEmpty()) throw new IllegalArgumentException("missing localization: " + language);
        return result;
    }
}
