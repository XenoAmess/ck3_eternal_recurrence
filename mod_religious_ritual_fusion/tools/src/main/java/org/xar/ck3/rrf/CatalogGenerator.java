package org.xar.ck3.rrf;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.xar.ck3.rrf.Contracts.Catalog;
import org.xar.ck3.rrf.Contracts.Definition;
import org.xar.ck3.rrf.Contracts.GeneratedFiles;
import org.xar.ck3.rrf.Contracts.Group;
import org.xar.ck3.rrf.Contracts.Kind;

/** Only writer of catalog runtime effects. Output uses exact source rule ASTs, never a permissive fallback. */
public final class CatalogGenerator {
    public record Generation(int definitionCount, int blockedCount, int faithModeExcluded, int religionTransferRestricted, List<String> runtimeFiles) { }
    private static final String HEADER = "# Generated by religious-ritual-fusion Java tools; edit the producer, then generate.\n";
    public Generation generate(Catalog catalog, Path source) throws IOException {
        Map<String, String> files = render(catalog);
        for (Map.Entry<String, String> entry : files.entrySet()) {
            Path target = source.resolve(entry.getKey()); Files.createDirectories(target.getParent());
            Files.writeString(target, "\ufeff" + HEADER + entry.getValue(), StandardCharsets.UTF_8);
        }
        Path directory = source.resolve("catalog"); Files.createDirectories(directory);
        byte[] bytes = Json.write(catalog); Files.write(directory.resolve("generated-catalog.json"), bytes);
        GeneratedFiles manifest = new GeneratedFiles(1, ReleaseBuilder.sha256(bytes), List.copyOf(files.keySet()));
        Files.write(directory.resolve("generated-files.json"), Json.write(manifest));
        return new Generation(catalog.definitions().size(), (int) catalog.definitions().stream().filter(d -> !d.blockedReasons().isEmpty()).count(), lockCount(catalog, "faith"), lockCount(catalog, "religion"), manifest.runtimeFiles());
    }
    public Map<String, String> render(Catalog catalog) {
        Map<String, String> files = new LinkedHashMap<>();
        List<String> init = new ArrayList<>(); List<String> select = new ArrayList<>(); List<String> validate = new ArrayList<>();
        for (Definition d : catalog.definitions()) {
            if (d.kind() == Kind.DOCTRINE) {
                init.add(initialize(d, catalog));
                select.add(select(d, catalog));
            }
            validate.add(validate(d, catalog));
        }
        for (Group group : catalog.groups()) {
            List<Definition> members = catalog.definitions().stream().filter(d -> d.kind() == Kind.DOCTRINE && d.group().equals(group.id())).toList();
            if (members.size() > 1) {
                String checks = String.join(" ", members.stream().map(d -> "is_target_in_variable_list = { name = rrf_selected_doctrines target = doctrine:" + d.id() + " }").toList());
                validate.add("if = { limit = { NOT = { calc_true_if = { amount <= 1 " + checks + " } } } add_character_flag = rrf_invalid_selection }\n");
            }
        }
        List<String> initCalls = slices(files, "initialize", init); List<String> selectCalls = slices(files, "select", select); List<String> validateCalls = slices(files, "validate", validate);
        String dispatch = effect("rrf_catalog_initialize_doctrines_effect", "clear_variable_list = rrf_candidate_doctrines\nclear_variable_list = rrf_selected_doctrines\n" + calls(initCalls))
                + effect("rrf_catalog_select_doctrine_effect", calls(selectCalls))
                + effect("rrf_catalog_validate_effect", "var:rrf_source_a_faith = { save_scope_as = rrf_projection_faith }\n" + calls(validateCalls)
                    + "every_in_list = { variable = rrf_selected_tenets save_scope_as = rrf_catalog_candidate scope:actor = { rrf_catalog_check_known_tenet_effect = yes } }\n"
                    + "every_in_list = { variable = rrf_selected_doctrines save_scope_as = rrf_catalog_candidate scope:actor = { rrf_catalog_check_known_doctrine_effect = yes } }\n")
                + knownEffect(catalog, Kind.TENET) + knownEffect(catalog, Kind.DOCTRINE);
        files.put("common/scripted_effects/rrf_catalog_dispatch_00.txt", dispatch);
        files.replaceAll((path, content) -> content.replaceAll("(?m)[ \\t]+$", "").stripTrailing() + "\n");
        return java.util.Collections.unmodifiableMap(new LinkedHashMap<>(files));
    }
    private static String initialize(Definition d, Catalog catalog) {
        if (!d.blockedReasons().isEmpty()) return "# " + d.id() + " disabled: " + String.join(", ", d.blockedReasons()) + "\n";
        String key = "doctrine:" + d.id();
        Group group = group(catalog, d);
        String bSource = group.lock().equals("religion") ? "" : "var:rrf_source_b = { rite_has_doctrine = " + d.id() + " }";
        String body = "if = { limit = { OR = { var:rrf_source_a = { rite_has_doctrine = " + d.id() + " } " + bSource + " } } add_to_variable_list = { name = rrf_candidate_doctrines target = " + key + " } }\n"
                + "if = { limit = { var:rrf_source_a = { rite_has_doctrine = " + d.id() + " } } add_to_variable_list = { name = rrf_selected_doctrines target = " + key + " } }\n";
        return group.lock().equals("faith") ? "if = { limit = { var:rrf_mode = flag:rite }\n" + body + "}\n" : body;
    }
    private static String knownEffect(Catalog catalog, Kind kind) {
        String type = kind == Kind.TENET ? "tenet" : "doctrine";
        String cases = String.join(" ", catalog.definitions().stream().filter(d -> d.kind() == kind).map(d -> "scope:rrf_catalog_candidate = " + type + ":" + d.id()).toList());
        return effect("rrf_catalog_check_known_" + type + "_effect", "if = { limit = { NOR = { " + cases + " } } add_character_flag = rrf_invalid_selection }\n");
    }
    private static String select(Definition d, Catalog catalog) {
        if (!d.blockedReasons().isEmpty()) return "# " + d.id() + " selection disabled\n";
        StringBuilder body = new StringBuilder("if = { limit = { scope:rrf_item = doctrine:").append(d.id()).append(" }\n");
        for (Definition sibling : catalog.definitions()) if (sibling.kind() == Kind.DOCTRINE && sibling.group().equals(d.group())) body.append("remove_list_variable = { name = rrf_selected_doctrines target = doctrine:").append(sibling.id()).append(" }\n");
        return body.append("add_to_variable_list = { name = rrf_selected_doctrines target = doctrine:").append(d.id()).append(" }\n}\n").toString();
    }
    private static String validate(Definition d, Catalog catalog) {
        String type = d.kind() == Kind.TENET ? "tenet" : "doctrine"; String list = d.kind() == Kind.TENET ? "rrf_selected_tenets" : "rrf_selected_doctrines";
        StringBuilder failure = new StringBuilder();
        if (!d.blockedReasons().isEmpty()) failure.append("always = no\n");
        else {
            if (!d.requiresDlc().isEmpty()) failure.append("scope:actor = { has_dlc_feature = ").append(d.requiresDlc()).append(" }\n");
            if (d.kind() == Kind.DOCTRINE) {
                Group group = group(catalog, d);
                if (group.lock().equals("faith")) failure.append("scope:actor = { var:rrf_mode = flag:rite }\n");
                if (group.lock().equals("religion")) failure.append("scope:actor = { var:rrf_source_a = { rite_has_doctrine = ").append(d.id()).append(" } }\n");
                failure.append(project(group.availableOnCreate())).append('\n');
            }
            failure.append(project(d.shown())).append('\n').append(project(d.canPick())).append('\n');
        }
        String candidate = type + ":" + d.id();
        // Native can_pick sees the other UI choices, not the candidate itself (syncretism/christology count self).
        String remove = "remove_from_list = selected_doctrines " + (d.kind() == Kind.TENET ? "remove_from_list = selected_tenets " : "");
        String restore = "add_to_list = selected_doctrines " + (d.kind() == Kind.TENET ? "add_to_list = selected_tenets " : "");
        return "if = { limit = { has_variable_list = " + list + " any_in_list = { variable = " + list + " this = " + candidate + " } }\n"
                + candidate + " = { " + remove + " }\n"
                + "if = { limit = { NOT = { var:rrf_source_a_faith = { " + failure + " } } } add_character_flag = rrf_invalid_selection }\n"
                + candidate + " = { " + restore + " }\n}\n";
    }
    private static String project(String source) {
        return RuleProjection.project(source);
    }
    private static Group group(Catalog catalog, Definition definition) { return catalog.groups().stream().filter(g -> g.id().equals(definition.group())).findFirst().orElseThrow(); }
    private static int lockCount(Catalog catalog, String lock) { return (int) catalog.definitions().stream().filter(d -> d.kind() == Kind.DOCTRINE && group(catalog, d).lock().equals(lock)).count(); }
    private static List<String> slices(Map<String, String> files, String family, List<String> fragments) {
        List<String> calls = new ArrayList<>();
        for (int offset = 0; offset < fragments.size(); offset += 10) {
            int number = offset / 10; String suffix = String.format(java.util.Locale.ROOT, "%02d", number);
            String name = "rrf_catalog_" + family + "_" + suffix + "_effect";
            files.put("common/scripted_effects/rrf_catalog_" + family + "_" + suffix + ".txt", effect(name, String.join("", fragments.subList(offset, Math.min(offset + 10, fragments.size())))));
            calls.add(name);
        }
        return calls;
    }
    private static String effect(String name, String body) { return name + " = {\n" + body + "}\n\n"; }
    private static String calls(List<String> names) { return String.join("\n", names.stream().map(name -> name + " = yes").toList()) + "\n"; }
}
