def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--spec', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--storage-admission', type=Path, required=True)
    args = parser.parse_args()
    spec = json.loads(args.spec.read_bytes()); admission = json.loads(args.storage_admission.read_bytes())
    output = args.output.resolve()
    require(not output.exists() and admission.get('status') == 'ADMITTED' and admission.get('machine_id') == MACHINE
        and any(output.is_relative_to(Path(root).resolve()) for root in admission['approved_output_roots'])
        and spec.get('metadata_ceiling_bytes') == MAX_OUTPUT, 'actual admitted create-only small output required')
    files = build_sources(spec)
    require(sum(map(len, files.values())) + 65536 <= MAX_OUTPUT, 'cold metadata output budget exceeded')
    output.mkdir(parents=True)
    for name, raw in files.items():
        with (output/name).open('xb') as stream:
            stream.write(raw)
    review = {'schema': 'xar.c11.native29-cold-controller-source-review/v1', 'machine_id': MACHINE,
        'observed_at_utc': datetime.now(timezone.utc).isoformat(), 'status': 'SOURCE_ONLY_NOT_RUNTIME_ADOPTED',
        'spec': pin(args.spec), 'storage_admission': pin(args.storage_admission),
        'files': [pin(output/name) for name in sorted(files)],
        'source_bytes': sum(map(len, files.values())), 'metadata_ceiling_bytes': MAX_OUTPUT,
        'Host_and_business_source_domains_separate': True,
        'fresh_Steam_offline_pixels_required': True, 'old_cold_or_SDK_requests_replayed': False,
        'actual_future_SAVE_prelaunch_Native29_publisher_OBS_pins_required': True,
        'Game_SDK_OBS_Native_process_calls': 0}
    with (output/'REVIEW.json').open('x', encoding='utf-8') as stream:
        json.dump(review, stream, ensure_ascii=False, indent=2); stream.write('\n')
    print(json.dumps(pin(output/'REVIEW.json')))


if __name__ == '__main__':
    main()
