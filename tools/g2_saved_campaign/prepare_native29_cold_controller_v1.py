def require(ok, why):
    if not ok:
        raise ValueError('Native29 cold source preparation denied: ' + why)


def pin(path):
    path = Path(path).resolve(strict=True); raw = path.read_bytes()
    return {'path': str(path), 'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()}


def source(ref, limit=1024**2):
    path = Path(ref['path']).resolve(strict=True)
    with path.open('rb') as stream:
        raw = stream.read(limit+1)
    require(len(raw) <= limit and len(raw) == ref['bytes'] and hashlib.sha256(raw).hexdigest() == ref['sha256'],
        'exact source bytes differ: ' + str(path))
    text = raw.decode('utf-8-sig'); ast.parse(text)
    return text


def mapped(value, replacements):
    for old, new in replacements:
        value = value.replace(old, new)
    return value


def namespace_port(text, replacements):
    """Change only module/identifier and literal namespace leaves, never code flow."""
    class Port(ast.NodeTransformer):
        def visit_Constant(self, node):
            if isinstance(node.value, str):
                return ast.copy_location(ast.Constant(mapped(node.value, replacements)), node)
            return node
        def visit_ImportFrom(self, node):
            node.module = mapped(node.module, replacements) if node.module else node.module
            return self.generic_visit(node)
        def visit_alias(self, node):
            node.name = mapped(node.name, replacements)
            return node
        def visit_Name(self, node):
            node.id = mapped(node.id, replacements)
            return node
        def visit_FunctionDef(self, node):
            node.name = mapped(node.name, replacements)
            return self.generic_visit(node)
        visit_AsyncFunctionDef = visit_FunctionDef
        visit_ClassDef = visit_FunctionDef
    expected = Port().visit(ast.parse(text))
    # Use whole source replacement only after AST establishes the permitted
    # names/literals; unexpected syntax changes cannot pass the exact AST check.
    changed = mapped(text, replacements)
    require(ast.dump(ast.parse(changed), include_attributes=False) == ast.dump(expected, include_attributes=False),
        'namespace port changed an unapproved AST field')
    return changed


def replace_span(text, node, new):
    lines = text.splitlines(keepends=True)
    return ''.join(lines[:node.lineno-1]) + new + '\n' + ''.join(lines[node.end_lineno:])


